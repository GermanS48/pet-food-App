create extension if not exists pgcrypto;

-- ---------- Catálogo ----------
-- La tabla ya existe en el proyecto con: id bigint, nombre, precio, created_at.
-- Estas sentencias la completan sin borrar datos.

create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  precio numeric(12, 2) not null default 0,
  created_at timestamptz not null default now()
);

alter table public.productos
  add column if not exists slug text,
  add column if not exists categoria text not null default 'perros',
  add column if not exists moneda text not null default 'ARS',
  add column if not exists imagen_url text,
  add column if not exists enlace text,
  add column if not exists vendedor text,
  add column if not exists calificacion numeric(2, 1),
  add column if not exists total_calificaciones integer not null default 0,
  add column if not exists cuotas text,
  add column if not exists envio text,
  add column if not exists envio_desde text,
  add column if not exists descuento text,
  add column if not exists etiqueta text,
  add column if not exists promocion text,
  add column if not exists promocion_url text,
  add column if not exists destacado boolean not null default false,
  add column if not exists activo boolean not null default true,
  add column if not exists datos_originales jsonb not null default '{}'::jsonb,
  add column if not exists updated_at timestamptz not null default now();

-- Normaliza el precio (la tabla original lo tenía como real).
alter table public.productos
  alter column precio type numeric(12, 2) using round(precio::numeric, 2);

update public.productos set precio = 0 where precio is null;
alter table public.productos alter column precio set default 0;
alter table public.productos alter column precio set not null;

update public.productos
set nombre = 'Producto sin nombre'
where nombre is null or length(trim(nombre)) = 0;
alter table public.productos alter column nombre set not null;

-- Restricciones (idempotentes).
do $$ begin
  alter table public.productos
    add constraint productos_categoria_check check (categoria in ('perros', 'gatos'));
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.productos
    add constraint productos_precio_check check (precio > 0);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.productos
    add constraint productos_calificacion_check
    check (calificacion is null or (calificacion >= 0 and calificacion <= 5));
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.productos
    add constraint productos_total_calificaciones_check check (total_calificaciones >= 0);
exception when duplicate_object then null; end $$;

create unique index if not exists productos_slug_key on public.productos (slug);
create index if not exists productos_categoria_idx on public.productos (categoria) where activo;
create index if not exists productos_destacado_idx on public.productos (destacado) where activo;
create index if not exists productos_nombre_idx on public.productos (nombre);

-- Si el id no tiene identidad ni default, le asigna una secuencia.
do $$
declare
  v_is_identity boolean;
  v_has_default boolean;
begin
  select (attidentity <> '') into v_is_identity
  from pg_attribute
  where attrelid = 'public.productos'::regclass and attname = 'id';

  select exists (
    select 1
    from pg_attrdef d
    join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum
    where d.adrelid = 'public.productos'::regclass and a.attname = 'id'
  ) into v_has_default;

  if not coalesce(v_is_identity, false) and not v_has_default then
    create sequence if not exists public.productos_id_seq;
    perform setval(
      'public.productos_id_seq',
      coalesce((select max(id) from public.productos), 0) + 1,
      false
    );
    alter table public.productos
      alter column id set default nextval('public.productos_id_seq');
    alter sequence public.productos_id_seq owned by public.productos.id;
  end if;
end $$;

-- ---------- Pedidos ----------

create table if not exists public.pedidos (
  id uuid primary key default gen_random_uuid(),
  cliente_nombre text not null,
  telefono text not null,
  email text,
  metodo_entrega text not null default 'delivery',
  direccion text,
  localidad text,
  notas text,
  total numeric(12, 2) not null default 0,
  estado text not null default 'pendiente',
  created_at timestamptz not null default now()
);

do $$ begin
  alter table public.pedidos
    add constraint pedidos_cliente_nombre_check
    check (length(trim(cliente_nombre)) between 2 and 160);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.pedidos
    add constraint pedidos_metodo_entrega_check
    check (metodo_entrega in ('delivery', 'pickup'));
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.pedidos
    add constraint pedidos_total_check check (total >= 0);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.pedidos
    add constraint pedidos_estado_check
    check (estado in ('pendiente', 'confirmado', 'entregado', 'cancelado'));
exception when duplicate_object then null; end $$;

create index if not exists pedidos_created_at_idx on public.pedidos (created_at desc);
create index if not exists pedidos_estado_idx on public.pedidos (estado);

create table if not exists public.pedido_items (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos (id) on delete cascade,
  producto_id bigint references public.productos (id) on delete set null,
  producto_nombre text not null,
  precio_unitario numeric(12, 2) not null,
  cantidad integer not null,
  subtotal numeric(12, 2) generated always as (precio_unitario * cantidad) stored,
  created_at timestamptz not null default now()
);

create index if not exists pedido_items_pedido_idx on public.pedido_items (pedido_id);
create index if not exists pedido_items_producto_idx on public.pedido_items (producto_id);

-- ---------- Mensajes de contacto ----------

create table if not exists public.mensajes (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  email text not null,
  mensaje text not null,
  atendido boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists mensajes_created_at_idx on public.mensajes (created_at desc);

-- ---------- Row Level Security ----------

alter table public.productos enable row level security;
alter table public.pedidos enable row level security;
alter table public.pedido_items enable row level security;
alter table public.mensajes enable row level security;

-- El catálogo es público (sólo productos activos).
drop policy if exists "productos_lectura_publica" on public.productos;
create policy "productos_lectura_publica"
  on public.productos
  for select
  to anon, authenticated
  using (activo = true);

-- Los mensajes se pueden crear desde la web, pero no leer.
drop policy if exists "mensajes_insercion_publica" on public.mensajes;
create policy "mensajes_insercion_publica"
  on public.mensajes
  for insert
  to anon, authenticated
  with check (
    length(trim(nombre)) between 2 and 160
    and length(trim(email)) between 5 and 254
    and email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'
    and length(trim(mensaje)) between 10 and 3000
  );

-- Pedidos y sus ítems: sin políticas públicas.
-- Se crean exclusivamente a través de la función crear_pedido (security definer).

-- ---------- Permisos ----------

grant usage on schema public to anon, authenticated;
grant select on public.productos to anon, authenticated;
grant insert on public.mensajes to anon, authenticated;

-- ---------- Crear pedido (RPC) ----------

create or replace function public.crear_pedido(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pedido public.pedidos;
  v_producto public.productos;
  v_items jsonb := payload -> 'items';
  v_item jsonb;
  v_cliente_nombre text := trim(coalesce(payload ->> 'cliente_nombre', ''));
  v_telefono text := trim(coalesce(payload ->> 'telefono', ''));
  v_email text := nullif(trim(coalesce(payload ->> 'email', '')), '');
  v_metodo text := coalesce(payload ->> 'metodo_entrega', 'delivery');
  v_direccion text := nullif(trim(coalesce(payload ->> 'direccion', '')), '');
  v_localidad text := nullif(trim(coalesce(payload ->> 'localidad', '')), '');
  v_notas text := nullif(trim(coalesce(payload ->> 'notas', '')), '');
  v_cantidad integer;
  v_total numeric(12, 2) := 0;
begin
  if length(v_cliente_nombre) < 2 then
    raise exception 'El nombre es obligatorio';
  end if;

  if length(regexp_replace(v_telefono, '\D', '', 'g')) < 8 then
    raise exception 'El teléfono no es válido';
  end if;

  if v_email is not null and v_email !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'El correo electrónico no es válido';
  end if;

  if v_metodo not in ('delivery', 'pickup') then
    raise exception 'Método de entrega inválido';
  end if;

  if v_metodo = 'delivery' and (v_direccion is null or length(v_direccion) < 4) then
    raise exception 'La dirección es obligatoria';
  end if;

  if v_metodo = 'delivery' and (v_localidad is null or length(v_localidad) < 2) then
    raise exception 'La localidad es obligatoria';
  end if;

  if v_items is null or jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 then
    raise exception 'El pedido no tiene productos';
  end if;

  if jsonb_array_length(v_items) > 50 then
    raise exception 'El pedido tiene demasiados productos';
  end if;

  insert into public.pedidos (
    cliente_nombre,
    telefono,
    email,
    metodo_entrega,
    direccion,
    localidad,
    notas,
    total,
    estado
  )
  values (
    v_cliente_nombre,
    v_telefono,
    v_email,
    v_metodo,
    v_direccion,
    v_localidad,
    v_notas,
    0,
    'pendiente'
  )
  returning * into v_pedido;

  for v_item in select * from jsonb_array_elements(v_items)
  loop
    v_cantidad := coalesce((v_item ->> 'cantidad')::integer, 0);
    if v_cantidad <= 0 or v_cantidad > 99 then
      raise exception 'Cantidad inválida';
    end if;

    if (v_item ->> 'producto_id') !~ '^\d+$' then
      raise exception 'Producto inválido o no disponible';
    end if;

    select * into v_producto
    from public.productos
    where id = (v_item ->> 'producto_id')::bigint
      and activo = true;

    if not found then
      raise exception 'Producto inválido o no disponible';
    end if;

    -- El nombre y el precio salen siempre de la base, no del cliente.
    insert into public.pedido_items (
      pedido_id,
      producto_id,
      producto_nombre,
      precio_unitario,
      cantidad
    )
    values (
      v_pedido.id,
      v_producto.id,
      v_producto.nombre,
      v_producto.precio,
      v_cantidad
    );

    v_total := v_total + (v_producto.precio * v_cantidad);
  end loop;

  update public.pedidos
  set total = v_total
  where id = v_pedido.id;

  return jsonb_build_object('pedido_id', v_pedido.id, 'total', v_total);
end;
$$;

revoke all on function public.crear_pedido(jsonb) from public;
grant execute on function public.crear_pedido(jsonb) to anon, authenticated;

notify pgrst, 'reload schema';
